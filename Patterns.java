import java.util.*;

public class Patterns {
    public static void main (String args[]){
        int n = 8;
        int m = 8;
        for(int i=0; i<n; i++) {
            for(int j=0;j<m;j++){
                System.out.print("*");
            }
            System.out.println();
        }
    }
    
}
